export type ApprovalStatus = "pending" | "approved" | "rejected" | "revision_requested";

export interface PurchaseRequestItem {
  namaBarang: string;
  qty: number;
  satuan: string;
  proyek: string;
  noSpk: string;
  // Optional link to the item master. The backend adds kodeBarang/supplierId/supplierName when it reads
  // the request back (null when the item has no supplier or was deleted); free-text rows have none of them.
  itemId?: number;
  kodeBarang?: string;
  supplierId?: number | null;
  supplierName?: string | null;
}

export interface PurchaseRequestPayload {
  bagian: string;
  namaPemohon: string;
  jabatan: string;
  tanggalPengajuan: string;
  items: PurchaseRequestItem[];
  notes?: string;
}

export interface ApprovalRequest {
  id: number;
  type: string;
  requestedBy: number;
  requestedByDomainId: number;
  payload: PurchaseRequestPayload | null;
  currentStepOrder: number;
  cycle: number;
  status: ApprovalStatus;
  // Only for APPROVED purchase requests; null otherwise.
  mappingStatus?: "NOT_STARTED" | "PARTIAL" | "COMPLETE" | null;
  createdAt: string;
}

export interface ApprovalAction {
  id: number;
  approvalRequestId: number;
  stepOrder: number;
  cycle: number;
  domainId: number;
  actorId: number;
  actorName?: string | null;
  action: "approved" | "rejected" | "revision_requested" | string;
  note: string | null;
  createdAt: string;
}

export interface ApprovalListParams {
  page?: number;
  pageSize?: number;
  search?: string;
  status?: ApprovalStatus;
  type?: string;
  domainId?: number;
  startDate?: string;
  endDate?: string;
  // Only purchase requests: whether at least one purchase order was made from the request.
  hasPurchaseOrder?: boolean;
}

